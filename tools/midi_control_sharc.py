#!/usr/bin/env python3
"""Assemble the SHARC program and write it as the boot stream's tail.

usage: midi_control_sharc.py --hx <hx-stomp-nam checkout>
                             [--out firmware/src/sharc_program.h]

The firmware boots the SHARC itself (docs/10). The stream it sends has two
parts, and only the second is ours:

  1. ADI's SPI boot kernel, 384 words: the first 1,536 bytes of the factory
     SHARC image at eMMC sector 0x8803. The firmware reads it off the card at
     start-up and checks its CRC32; it is never copied here.
  2. The tail this tool writes, in the factory stream's block format:

         {5, n, 0x8C100}   firmware/sharc/passthru.asm with audio_init.asm
                           appended, n 48-bit instructions packed three words
                           to two
         {0, w1, w2}       FINAL_INIT; w1:w2 carry one instruction, as the
                           factory header does
         384 words         256 instructions over 0x8C000..0x8C0FF: RTI at the
                           SPI vector 0x8C030, JUMP 0x8C100 in every other slot

     ADI's kernel ends by DMAing the FINAL_INIT payload over itself and taking
     the DMA-done interrupt; the RTI resumes in the payload, and a jump in every
     slot reaches the program whichever way the kernel leaves.

Each word is written big-endian, the order the factory image stores its words
in, so the firmware sends the tail exactly as it sends the kernel.

The assembler is hx-stomp-nam's tools/sharc/sasm.py (GPL-3.0), run from that
checkout; nothing of it is copied here. What this writes is the assembled
output of our own sources, and it is committed so that building the firmware
does not need the checkout. Re-run this after changing anything in
firmware/sharc/.
"""
import argparse
import os
import struct
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SHARC = os.path.join(ROOT, "firmware", "sharc")
SOURCES = ["passthru.asm", "audio_init.asm"]
PROG_BASE = 0x8C100
SPI_VECTOR_SLOT = 0x30
TAG_FINAL_INIT, TAG_INIT_L48 = 0, 5


def pack48(ins):
    """48-bit instructions -> 32-bit words, as the loader packs them (two to three)."""
    assert len(ins) % 2 == 0
    raw = b"".join(i.to_bytes(6, "little") for i in ins)
    return list(struct.unpack("<%dI" % (len(raw) // 4), raw))


def tail(sasm, paths):
    text = "\n".join(open(p).read() for p in paths)
    secs, _ = sasm.assemble(text, " + ".join(os.path.basename(p) for p in paths))
    pm = [s for s in secs if s.kind == "pm"]
    if len(pm) != 1 or pm[0].addr != PROG_BASE or len(secs) != 1:
        sys.exit("expected exactly one section, pm at %#x" % PROG_BASE)
    ins = list(pm[0].words)
    if len(ins) % 2:
        ins.append(0)                                   # a NOP, to an even count

    def enc(src):
        s, _ = sasm.assemble(".section pm 0x8c000\n%s\n" % src, "tail")
        return s[0].words[0]

    jump, rti = enc("JUMP %#x;" % PROG_BASE), enc("RTI;")
    slots = [jump] * 256
    slots[SPI_VECTOR_SLOT] = rti

    words = [TAG_INIT_L48, len(ins), PROG_BASE] + pack48(ins)
    words += [TAG_FINAL_INIT, (jump & 0xFFFF) << 16, jump >> 16] + pack48(slots)
    return words, len(ins)


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[1])
    ap.add_argument("--hx", required=True, help="hx-stomp-nam checkout (for its assembler)")
    ap.add_argument("--out", default=os.path.join(ROOT, "firmware", "src", "sharc_program.h"))
    a = ap.parse_args()

    sys.path.insert(0, os.path.join(a.hx, "tools", "sharc"))
    import sasm

    words, n = tail(sasm, [os.path.join(SHARC, s) for s in SOURCES])
    raw = struct.pack(">%dI" % len(words), *words)
    with open(a.out, "w", newline="\n") as f:
        f.write("/* Generated by tools/midi_control_sharc.py from firmware/sharc/%s - do not\n"
                " * edit. The SHARC boot stream after ADI's kernel: the program, %d\n"
                " * instructions at 0x%X, then FINAL_INIT. docs/10. */\n"
                % (" + ".join(SOURCES), n, PROG_BASE))
        f.write("#ifndef MIDI_CONTROL_SHARC_PROGRAM_H\n#define MIDI_CONTROL_SHARC_PROGRAM_H\n\n")
        f.write("#include <stdint.h>\n\n")
        f.write("#define SHARC_PROGRAM_WORDS %du\n" % len(words))
        f.write("static const uint8_t k_sharc_program[] __attribute__((aligned(4))) = {\n")
        for j in range(0, len(raw), 16):
            f.write("    " + ", ".join("0x%02x" % b for b in raw[j:j + 16]) + ",\n")
        f.write("};\n\n#endif\n")
    print("{5, %d, %#x} + %d words, FINAL_INIT + 384: %d words -> %s"
          % (n, PROG_BASE, 3 * n // 2, len(words), os.path.relpath(a.out, ROOT)))


if __name__ == "__main__":
    main()
